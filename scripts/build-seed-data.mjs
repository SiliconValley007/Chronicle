// Ingests content/*.json (objects) and content/batch-*.mjs (compact tuples) → data.js. Run: npm run seed
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
const T = {
    Bahamas: "the_Bahamas",
    "Democratic Republic of the Congo": "the_Democratic_Republic_of_the_Congo",
    "Côte d’Ivoire": "Ivory_Coast",
  },
  dflt = (c) => "History_of_" + (T[c] || c.replace(/ /g, "_")),
  rows = [],
  norm = (r) => ({ ...r, title: r.t, body: r.b, impact: r.sig });
for (const f of readdirSync("content").sort()) {
  if (f.endsWith(".json"))
    for (const r of JSON.parse(readFileSync("content/" + f, "utf8")))
      rows.push(norm(r));
  else if (/^batch-.*\.mjs$/.test(f))
    for (const R of (await import(pathToFileURL(resolve("content", f))))
      .default) {
      const [c, y, era, th, t, b, sig, sl, n] =
        R.length === 6 ? [R[0], R[1], R[2], "Power", R[3], R[4], R[5]] : R;
      if (!sig) throw Error("missing sig: " + R[0]);
      const slug = sl || dflt(c),
        m = y.match(/\d{3,4}/),
        s = /BCE/.test(y) ? -m[0] : +m[0];
      rows.push(
        norm({
          c,
          y,
          s,
          era,
          th,
          t,
          b,
          sig,
          n: n || "",
          src: {
            t: decodeURIComponent(slug).replace(/_/g, " "),
            u: "https://en.wikipedia.org/wiki/" + slug,
          },
        }),
      );
    }
}
writeFileSync(
  "data.js",
  `// GENERATED by scripts/build-seed-data.mjs from content/ — do not edit by hand.
import {REG} from './countries.js';
const slug = s => s.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
export const LICENSE = 'CC BY-SA 4.0 (linked Wikipedia sources; text paraphrased)';
export const ITEMS = ${JSON.stringify(rows)}.map(r => ({...r, id: \`\${slug(r.c||'world')}-\${r.s}-\${slug(r.t)}\`, license: LICENSE}));
export const COUNTRIES = REG.map(r => r.name);
export const THEMES = ['Power','Ideas','Exploration','Rights','Science','Culture'];
`,
);
console.log(rows.length + " rows compiled");
